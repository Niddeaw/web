                confirmButtonText: '✅ แก้ไขต่อ (โหลดข้อมูลเดิม)',
                denyButtonText: '🗑️ เริ่มใหม่ (ลบข้อมูลเดิม)',
                cancelButtonText: '❌ ยกเลิก',
                confirmButtonColor: '#3085d6',
